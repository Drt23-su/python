# Lista de números
numeros = [1, 2, 3, 4, 5]

# Inicializar la variable para la suma
suma_total = 0

# Usar un bucle para sumar los elementos de la lista
for numero in numeros:
    suma_total += numero  # Sumar cada número a la suma total

# Imprimir el resultado
print(f"La suma de todos los elementos es: {suma_total}")